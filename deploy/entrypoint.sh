#!/usr/bin/env bash
# ============================================================================
# fcloud-ci-hub 容器入口（§11.2 / §11.3）
#
# 职责：
# 1. 目录准备（/data/config-hub/{pg,storage,backups}）
# 2. PG 首次 initdb（判断 PG_VERSION 是否存在，§11.2）
# 3. 渲染 nginx 配置（envsubst，上游端口取 FCLOUD_SERVER_PORT，默认 8081）
# 4. 启动顺序由 supervisord priority 保证；本脚本只做一次性准备
#
# 数据库 bootstrap（建库建用户）放到后台任务里，等 PG 起来后执行。
# ============================================================================
set -euo pipefail

DATA_ROOT="${FCLOUD_DATA_ROOT:-/data/config-hub}"
PGDATA="${DATA_ROOT}/pg"
STORAGE_DIR="${FCLOUD_STORAGE_ROOT:-${DATA_ROOT}/storage}"
BACKUP_DIR="${FCLOUD_BACKUP_DIR:-${DATA_ROOT}/backups}"

DB_NAME="${FCLOUD_DB_NAME:-fcloud_ci_hub}"
DB_USER="${FCLOUD_DB_USER:-fcloud}"
DB_PASSWORD="${FCLOUD_DB_PASSWORD:-fcloud}"
SERVER_PORT="${FCLOUD_SERVER_PORT:-8081}"

log() { echo "[entrypoint] $*"; }

mkdir -p "${DATA_ROOT}" "${STORAGE_DIR}" "${BACKUP_DIR}" \
         /var/log/supervisor /var/log/nginx /run/nginx /var/run/postgresql /tmp

# ---------------------------------------------------------------------------
# 1. PG 数据目录准备（initdb 交给 postgres 官方 docker-entrypoint.sh）
#
#    supervisord 用 `docker-entrypoint.sh postgres -D /data/config-hub/pg` 启动 PG：
#    - 目录为空时：官方脚本执行 initdb，并按 POSTGRES_DB/USER/PASSWORD 建库建用户
#    - 目录已有 PG_VERSION 时：直接启动（§11.2 的幂等要求）
#    这里只负责目录与权限。
# ---------------------------------------------------------------------------
if [ ! -f "${PGDATA}/PG_VERSION" ]; then
    log "empty PG data directory at ${PGDATA}; official entrypoint will run initdb"
    rm -rf "${PGDATA}"
    mkdir -p "${PGDATA}"
else
    log "existing PG data directory detected (PG_VERSION present)"
fi
chown -R postgres:postgres "${PGDATA}"
chmod 700 "${PGDATA}"

# ---------------------------------------------------------------------------
# 2. 渲染 nginx 配置
# ---------------------------------------------------------------------------log "rendering nginx config (upstream port ${SERVER_PORT})"
export FCLOUD_SERVER_PORT="${SERVER_PORT}"
export FCLOUD_GITLAB_LITE_HOST="${FCLOUD_GITLAB_LITE_HOST:-127.0.0.1}"
export FCLOUD_GITLAB_LITE_PORT="${FCLOUD_GITLAB_LITE_PORT:-8929}"
envsubst '${FCLOUD_SERVER_PORT} ${FCLOUD_GITLAB_LITE_HOST} ${FCLOUD_GITLAB_LITE_PORT}' \
    < /etc/nginx/fcloud.conf.template \
    > /etc/nginx/conf.d/fcloud.conf

# ---------------------------------------------------------------------------
# 3. 导出给 supervisord 子进程的环境（/etc/environment 不生效，用 shell 导出）
# ---------------------------------------------------------------------------
export FCLOUD_DB_HOST=127.0.0.1
export FCLOUD_DB_PORT=5432
export FCLOUD_DB_NAME="${DB_NAME}"
export FCLOUD_DB_USER="${DB_USER}"
export FCLOUD_DB_PASSWORD="${DB_PASSWORD}"
export FCLOUD_REDIS_HOST=127.0.0.1
export FCLOUD_REDIS_PORT=6379
export FCLOUD_SERVER_PORT="${SERVER_PORT}"
export FCLOUD_STORAGE_ROOT="${STORAGE_DIR}"
export FCLOUD_BACKUP_DIR="${BACKUP_DIR}"
export FCLOUD_MASTER_KEY_FILE="${DATA_ROOT}/master.key"

# supervisor 会把当前进程环境传给子进程（supervisord 继承这里的 export）
# 这里额外写一份 env 文件，便于排障时核对实际生效的配置
{
  echo "# generated by entrypoint at $(date -Iseconds)"
  echo "FCLOUD_DB_HOST=${FCLOUD_DB_HOST}"
  echo "FCLOUD_DB_PORT=${FCLOUD_DB_PORT}"
  echo "FCLOUD_DB_NAME=${FCLOUD_DB_NAME}"
  echo "FCLOUD_DB_USER=${FCLOUD_DB_USER}"
  echo "FCLOUD_REDIS_HOST=${FCLOUD_REDIS_HOST}"
  echo "FCLOUD_REDIS_PORT=${FCLOUD_REDIS_PORT}"
  echo "FCLOUD_SERVER_PORT=${FCLOUD_SERVER_PORT}"
  echo "FCLOUD_STORAGE_ROOT=${FCLOUD_STORAGE_ROOT}"
  echo "FCLOUD_BACKUP_DIR=${FCLOUD_BACKUP_DIR}"
  echo "FCLOUD_MASTER_KEY_FILE=${FCLOUD_MASTER_KEY_FILE}"
} > /data/config-hub/runtime-env.txt 2>/dev/null || true

# ---------------------------------------------------------------------------
# 4. 后台等待 PG 就绪 → 建库建用户（幂等）
# ---------------------------------------------------------------------------
(
  log "background: waiting for PostgreSQL ..."
  for i in $(seq 1 120); do
      if pg_isready -h 127.0.0.1 -p 5432 -q 2>/dev/null; then
          log "background: PostgreSQL is ready"
          break
      fi
      sleep 1
  done

  if ! su-exec postgres psql -tAc \
        "SELECT 1 FROM pg_roles WHERE rolname='${DB_USER}'" 2>/dev/null | grep -q 1; then
      su-exec postgres psql -c \
        "CREATE ROLE ${DB_USER} LOGIN PASSWORD '${DB_PASSWORD}'" >/dev/null 2>&1 || true
      log "background: role ${DB_USER} created"
  fi

  if ! su-exec postgres psql -tAc \
        "SELECT 1 FROM pg_database WHERE datname='${DB_NAME}'" 2>/dev/null | grep -q 1; then
      su-exec postgres createdb -O "${DB_USER}" "${DB_NAME}" >/dev/null 2>&1 || true
      log "background: database ${DB_NAME} created"
  fi

  # PG15+ public schema 授权
  su-exec postgres psql -d "${DB_NAME}" -c \
      "GRANT ALL ON SCHEMA public TO ${DB_USER}" >/dev/null 2>&1 || true

  log "background: database bootstrap complete"
) > /var/log/supervisor/bootstrap.log 2>&1 &

log "preparation done; handing over to supervisord"
exec "$@"
